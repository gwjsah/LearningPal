/**
 * Client service for local LLM question generation, progress polling, and teacher review/approval.
 */
export const aiService = {
  /**
   * Retrieves status and availability of local LLM serving.
   */
  getStatus: () => apiRequest('/teacher/ai/status'),

  /**
   * Submits a new asynchronous AI question drafting job from an uploaded file resource.
   */
  createJob: (subjectId, fileId, data) =>
    apiRequest(`/teacher/subjects/${subjectId}/files/${fileId}/ai/generate`, {
      method: 'POST',
      body: JSON.stringify(data),
    }),

  /**
   * Retrieves status and progress of an active or completed job.
   */
  getJob: (jobId) => apiRequest(`/teacher/ai/jobs/${jobId}`),

  /**
   * Requests cancellation of a queued or running generation job.
   */
  cancelJob: (jobId) =>
    apiRequest(`/teacher/ai/jobs/${jobId}/cancel`, {
      method: 'POST',
    }),

  /**
   * Lists generation jobs, optionally filtered by subject.
   */
  listJobs: (subjectId) =>
    apiRequest(subjectId ? `/teacher/ai/jobs?subjectId=${subjectId}` : '/teacher/ai/jobs'),

  /**
   * Retrieves question drafts generated by a job.
   */
  getDrafts: (jobId) => apiRequest(`/teacher/ai/jobs/${jobId}/drafts`),

  /**
   * Edits a draft prior to approval.
   */
  updateDraft: (draftId, data) =>
    apiRequest(`/teacher/ai/drafts/${draftId}`, {
      method: 'PATCH',
      body: JSON.stringify(data),
    }),

  /**
   * Approves a single draft, publishing it to the teacher's question bank.
   */
  approveDraft: (draftId) =>
    apiRequest(`/teacher/ai/drafts/${draftId}/approve`, {
      method: 'POST',
    }),

  /**
   * Rejects a single draft.
   */
  rejectDraft: (draftId) =>
    apiRequest(`/teacher/ai/drafts/${draftId}/reject`, {
      method: 'POST',
    }),

  /**
   * Bulk-approves verified drafts.
   */
  approveSelected: (jobId, draftIds) =>
    apiRequest(`/teacher/ai/jobs/${jobId}/approve-selected`, {
      method: 'POST',
      body: JSON.stringify({ draftIds }),
    }),
};
